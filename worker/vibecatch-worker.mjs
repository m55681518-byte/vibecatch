#!/usr/bin/env node
// VibeCatch Remote Worker — dependency-free Node ESM HTTP server
// Node >=18, zero npm dependencies (builtins only).
// Importing MUST NOT start the server; server starts only when executed directly.

import http from 'node:http';
import { URL } from 'node:url';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

// ---------------------------------------------------------------------------
// corsHeaders — CORS + Private Network headers for browser PWA access
// ---------------------------------------------------------------------------

export function corsHeaders() {
  return {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET,OPTIONS',
    'Access-Control-Allow-Headers': '*',
    'Access-Control-Allow-Private-Network': 'true',
    'Content-Type': 'application/json',
  };
}

const CORS_ONLY = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET,OPTIONS',
  'Access-Control-Allow-Headers': '*',
  'Access-Control-Allow-Private-Network': 'true',
};

// ---------------------------------------------------------------------------
// parseRangeHeader — parse Range header or query value
// ---------------------------------------------------------------------------

export function parseRangeHeader(h) {
  if (typeof h !== 'string') return null;
  const m = /^bytes=(\d+)-(\d*)$/.exec(h);
  if (!m) return null;
  const start = Number(m[1]);
  const end = m[2] === '' ? undefined : Number(m[2]);
  return { start, end };
}

// ---------------------------------------------------------------------------
// sanitizeFilename — strip illegal chars for Content-Disposition
// ---------------------------------------------------------------------------

export function sanitizeFilename(name) {
  return String(name || '').replace(/[^A-Za-z0-9 ._-]/g, '_').substring(0, 200);
}

// ---------------------------------------------------------------------------
// validVideoId — YouTube video IDs are 11 chars [A-Za-z0-9_-] but we
// accept anything that looks like one (not a plain all-caps word).
// ---------------------------------------------------------------------------

const YT_ID_RE = /^[A-Za-z0-9_-]{4,}$/;

export function validVideoId(id) {
  if (!id || typeof id !== 'string') return false;
  if (!YT_ID_RE.test(id)) return false;
  // Reject all-uppercase words — real YouTube IDs always contain
  // at least one lowercase letter or digit mixed in.
  if (/^[A-Z]+$/.test(id)) return false;
  return true;
}

